/** Linear RGB of a blackbody at `kelvin` (clamped to 1000..12000 K), with a fluorescent green shift: the green
 * channel is scaled by (1 + greenTint) before renormalising. Max component 1. */
export function kelvinToLinearRGB(kelvin: number, greenTint: number): Vec3 {
  const k = kelvin < K0 ? K0 : kelvin > K1 ? K1 : kelvin;
  const f = (k - K0) / STEP;
  let i = Math.floor(f);
  if (i >= (K1 - K0) / STEP) i = (K1 - K0) / STEP - 1;
  const t = f - i;
  const a = i * 3, b = a + 3;
  let r = TABLE[a] + (TABLE[b] - TABLE[a]) * t;
  let g = (TABLE[a + 1] + (TABLE[b + 1] - TABLE[a + 1]) * t) * (1 + greenTint);
  let bl = TABLE[a + 2] + (TABLE[b + 2] - TABLE[a + 2]) * t;
  const m = Math.max(r, g, bl);
  r /= m; g /= m; bl /= m;
  return [r, g, bl];
}
